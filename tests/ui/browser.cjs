"use strict";

const assert = require("node:assert/strict");
const { chromium } = require("playwright");

async function run() {
  if (process.env.ROUTETUS_UI_TEST_DISPOSABLE !== "1") throw new Error("This test creates routes. Set ROUTETUS_UI_TEST_DISPOSABLE=1 only for a disposable deployment.");
  const base = process.env.ROUTETUS_UI_URL || "http://127.0.0.1:9180";
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
    const errors = [];
    page.setDefaultTimeout(8000);
    page.on("pageerror", (error) => errors.push(error.message));
    page.on("request", (request) => assert.equal(request.headers().authorization, undefined, "Browser received the server token"));
    const config = async () => {
      const response = await fetch(base + "/api/config");
      assert.equal(response.status, 200);
      return { body: await response.json(), etag: response.headers.get("etag") };
    };
    const before = await config();
    assert.ok(before.body.upstreams.length, "An existing upstream is required");
    await page.goto(base);
    await page.getByRole("status").filter({ hasText: "Connected" }).waitFor();
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    await page.getByRole("button", { name: "Handler guide", exact: true }).click();
    await page.getByRole("heading", { name: "access_log", exact: true }).waitFor();
    await page.getByText("Logs request method, status, duration, size, and route ID.", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Close handler guide" }).click();
    const suffix = Date.now().toString(36);
    const id = "ui-" + suffix;
    let selectedUpstream = before.body.upstreams[0].id;
    const fill = async (routeID, path) => {
      await page.getByLabel("Route ID", { exact: true }).fill(routeID);
      await page.getByLabel("Request path", { exact: true }).fill(path);
      await page.getByLabel("Upstream", { exact: true }).selectOption(selectedUpstream);
    };
    const submit = page.getByRole("button", { name: "Create route" });
    await page.locator("#new-upstream").click();
    await page.getByLabel("Upstream ID", { exact: true }).fill(id + "-upstream");
    await page.getByLabel("Backend URLs", { exact: true }).fill(before.body.upstreams[0].targets[0].url);
    await page.getByRole("button", { name: "Create upstream", exact: true }).click();
    await page.locator("#upstream-dialog").waitFor({ state: "hidden" });
    selectedUpstream = id + "-upstream";
    assert.equal(await page.getByLabel("Upstream", { exact: true }).inputValue(), selectedUpstream);
    await page.locator("#new-handler").click();
    await page.getByLabel("Handler ID", { exact: true }).fill(id + "-log");
    await page.getByLabel("Handler type", { exact: true }).selectOption("access_log");
    const parameter = page.getByLabel("sample every", { exact: true });
    assert.equal(await parameter.getAttribute("type"), "number");
    await parameter.fill("3");
    await page.getByRole("button", { name: "Create handler", exact: true }).click();
    await page.locator("#handler-dialog").waitFor({ state: "hidden" });
    assert.equal(await page.locator('input[name="handlers"][value="' + id + '-log"]').isChecked(), true);
    const created = await config();
    assert.equal(created.body.handlers.find((handler) => handler.id === id + "-log").options.sample_every, 3);
    assert.equal(created.body.upstreams.find((upstream) => upstream.id === selectedUpstream).targets[0].url, before.body.upstreams[0].targets[0].url);
    await fill(id, "/" + id);
    if (before.body.handlers.some((handler) => handler.id === "powered" && handler.enabled !== false)) await page.locator('input[name="handlers"][value="powered"]').check();
    await submit.click();
    await page.locator("#notice").filter({ hasText: `Route "${id}" created.` }).waitFor();
    await page.getByText(id, { exact: true }).waitFor();
    const saved = (await config()).body.routes.find((route) => route.id === id);
    assert.equal(saved.path, "/" + id);
    assert.equal(saved.upstream, selectedUpstream);
    assert.ok(saved.handlers.includes(id + "-log"));
    assert.deepEqual(saved.methods, ["GET"]);
    await fill(id + "-retry", "/" + id + "-retry");
    const current = await config();
    const external = await fetch(base + "/api/routes", { method: "POST", headers: { "Origin": base, "Content-Type": "application/json", "If-Match": current.etag }, body: JSON.stringify({ id: id + "-external", path: "/" + id + "/<img src=x onerror=window.uiXss=1>", upstream: saved.upstream, handlers: [], methods: ["GET"], prefix: false, strip_prefix: false }) });
    assert.ok(external.ok, await external.text());
    await submit.click();
    await page.locator("#notice").filter({ hasText: "Configuration changed while you were editing" }).waitFor();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).inputValue(), id + "-retry");
    assert.equal(await page.evaluate(() => window.uiXss), undefined);
    await submit.click();
    await page.locator("#notice").filter({ hasText: `Route "${id}-retry" created.` }).waitFor();
    await fill(id + "-invalid", "/api//invalid");
    await submit.click();
    await page.locator("#notice.error").waitFor();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).inputValue(), id + "-invalid");
    assert.ok(!(await config()).body.routes.some((route) => route.id === id + "-invalid"));
    await page.locator("#search").fill(id);
    assert.equal(await page.locator("#routes tr").count(), 3);
    await page.locator("#search").fill("");
    await page.getByRole("button", { name: "Delete route " + id + "-retry", exact: true }).click();
    await page.locator("#delete-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.ok((await config()).body.routes.some((route) => route.id === id + "-retry"));
    await page.getByRole("button", { name: "Delete route " + id + "-retry", exact: true }).click();
    const deleteState = await config();
    const concurrent = await fetch(base + "/api/handlers", { method: "POST", headers: { "Origin": base, "Content-Type": "application/json", "If-Match": deleteState.etag }, body: JSON.stringify({ id: id + "-concurrent", type: "access_log", version: 1, options: { sample_every: 1 } }) });
    assert.ok(concurrent.ok, await concurrent.text());
    await page.locator("#confirm-delete").click();
    await page.locator("#delete-error").filter({ hasText: "Configuration changed" }).waitFor();
    await page.locator("#confirm-delete").click();
    await page.locator("#notice").filter({ hasText: `Route "${id}-retry" deleted.` }).waitFor();
    assert.ok(!(await config()).body.routes.some((route) => route.id === id + "-retry"));
    await page.locator("#route-form").evaluate((form) => form.reset());
    await page.getByRole("button", { name: "Refresh" }).click();
    await page.locator("#notice").filter({ hasText: "Configuration refreshed." }).waitFor();
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile page overflows horizontally");
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
    console.log("Browser checks passed: handler guide, typed handler options, upstream registration, route creation/deletion, generation conflict/retry, validation, safe text, filtering, and mobile layout.");
  } finally { await browser.close(); }
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
