"use strict";

const assert = require("node:assert/strict");
const { chromium } = require("playwright");
const checkSystemTheme = require("./theme.cjs");
const checkHandlerChoices = require("./handlers.cjs");

async function run() {
  if (process.env.ROUTETUS_UI_TEST_DISPOSABLE !== "1") throw new Error("This test creates routes. Set ROUTETUS_UI_TEST_DISPOSABLE=1 only for a disposable deployment.");
  const base = process.env.ROUTETUS_UI_URL || "http://127.0.0.1:9180";
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
    const page = await context.newPage();
    const errors = [];
    page.setDefaultTimeout(8000);
    page.on("pageerror", (error) => errors.push(error.message));
    page.on("request", (request) => assert.equal(request.headers().authorization, undefined, "Browser received the server token"));
    const config = async () => {
      const response = await fetch(base + "/api/config");
      assert.equal(response.status, 200);
      return { body: await response.json(), etag: response.headers.get("etag") };
    };
    const mutate = async (method, path, body) => {
      const current = await config();
      const response = await fetch(base + path, { method, headers: { Origin: base, "Content-Type": "application/json", "If-Match": current.etag }, body: body === undefined ? undefined : JSON.stringify(body) });
      assert.ok(response.ok, await response.text());
    };
    const refresh = async () => {
      await page.getByRole("button", { name: "Refresh" }).click();
      await page.locator("#notice").filter({ hasText: "Configuration refreshed." }).waitFor();
    };
    const before = await config();
    assert.ok(before.body.upstreams.length, "An existing upstream is required");
    await page.goto(base);
    await page.getByRole("status").filter({ hasText: "Connected" }).waitFor();
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    await checkHandlerChoices(page, before.body);
    await checkSystemTheme(page);
    await page.getByRole("button", { name: "Upstreams", exact: true }).click();
    await page.getByRole("heading", { name: "Configured upstreams", exact: true }).waitFor();
    assert.equal(await page.locator("#upstreams tr").count(), before.body.upstreams.length);
    await page.getByRole("button", { name: "Routes", exact: true }).click();
    await page.getByRole("button", { name: "Handler guide", exact: true }).click();
    await page.getByRole("heading", { name: "powered_by", exact: true }).waitFor();
    await page.getByText("Adds an X-Powered-By response header.", { exact: true }).waitFor();
    await page.getByRole("button", { name: "Close handler guide" }).click();
    const suffix = Date.now().toString(36);
    const id = "ui-" + suffix;
    let selectedUpstream = before.body.upstreams[0].id;
    const fill = async (routeID, path) => {
      await page.getByLabel("Route ID", { exact: true }).fill(routeID);
      await page.getByLabel("Request path", { exact: true }).fill(path);
      await page.getByLabel("Upstream", { exact: true }).selectOption(selectedUpstream);
    };
    const submit = page.getByRole("button", { name: "Create route" });
    assert.equal(await page.getByRole("button", { name: "New upstream", exact: false }).count(), 0);
    await fill(id, "/" + id);
    await page.getByRole("button", { name: "Upstreams", exact: true }).click();
    await page.getByRole("button", { name: "Add upstream", exact: false }).click();
    await page.getByLabel("Upstream ID", { exact: true }).fill(id + "-upstream");
    await page.getByLabel("Backend URLs", { exact: true }).fill(before.body.upstreams[0].targets[0].url);
    await page.getByRole("button", { name: "Create upstream", exact: true }).click();
    await page.locator("#upstream-dialog").waitFor({ state: "hidden" });
    selectedUpstream = id + "-upstream";
    await page.getByRole("button", { name: "Routes", exact: true }).click();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).inputValue(), id);
    assert.equal(await page.getByLabel("Request path", { exact: true }).inputValue(), "/" + id);
    assert.equal(await page.getByLabel("Upstream", { exact: true }).inputValue(), selectedUpstream);
    const routeHandler = before.body.handlers.find((handler) => !(before.body.global_handlers || []).includes(handler.id) && handler.enabled !== false);
    assert.ok(routeHandler, "An existing route handler is required");
    const created = await config();
    assert.equal(created.body.upstreams.find((upstream) => upstream.id === selectedUpstream).targets[0].url, before.body.upstreams[0].targets[0].url);
    await fill(id, "/" + id);
    await page.locator('input[name="handlers"][value="' + routeHandler.id + '"]').check();
    await submit.click();
    await page.locator("#notice").filter({ hasText: `Route "${id}" created.` }).waitFor();
    await page.locator("#routes").getByText(id, { exact: true }).waitFor();
    const saved = (await config()).body.routes.find((route) => route.id === id);
    assert.equal(saved.path, "/" + id);
    assert.equal(saved.upstream, selectedUpstream);
    assert.deepEqual(saved.handlers, [routeHandler.id]);
    assert.deepEqual(saved.methods, ["GET"]);
    const legacyGlobal = before.body.global_handlers[0];
    const handlerOrder = [routeHandler.id, legacyGlobal];
    await mutate("PATCH", "/api/routes/" + id, { host: "example.com", priority: 42, request_timeout: "7s", metrics: false, handlers: handlerOrder, methods: ["PROPFIND", "GET"] });
    await refresh();
    await page.getByRole("button", { name: "Edit route " + id, exact: true }).click();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).getAttribute("readonly"), "");
    await page.getByLabel("Request path", { exact: true }).fill("/" + id + "-edited");
    assert.equal(await page.locator('input[name="handlers"][value="' + legacyGlobal + '"]').count(), 0);
    await page.locator('input[name="methods"][value="POST"]').check();
    await page.locator("#prefix").check();
    await page.locator("#strip-prefix").check();
    await mutate("PATCH", "/api/routes/" + id, { priority: 43 });
    await page.getByRole("button", { name: "Save route", exact: true }).click();
    await page.locator("#notice").filter({ hasText: "Configuration changed while you were editing" }).waitFor();
    assert.equal(await page.getByLabel("Request path", { exact: true }).inputValue(), "/" + id + "-edited");
    await page.getByRole("button", { name: "Save route", exact: true }).click();
    await page.locator("#notice").filter({ hasText: `Route "${id}" updated.` }).waitFor();
    const edited = (await config()).body.routes.find((route) => route.id === id);
    assert.equal(edited.host, "example.com"); assert.equal(edited.priority, 43); assert.equal(edited.request_timeout, "7s"); assert.equal(edited.metrics, false);
    assert.deepEqual(edited.handlers, handlerOrder); assert.deepEqual(edited.methods, ["PROPFIND", "GET", "POST"]);
    assert.equal(edited.prefix, true); assert.equal(edited.strip_prefix, true);
    assert.equal(edited.path, "/" + id + "-edited");
    await page.getByRole("button", { name: "Edit route " + id, exact: true }).click();
    await page.getByLabel("Request path", { exact: true }).fill("/api//invalid");
    await page.getByRole("button", { name: "Save route", exact: true }).click();
    await page.locator("#notice.error").waitFor();
    assert.equal((await config()).body.routes.find((route) => route.id === id).path, edited.path);
    await page.getByRole("button", { name: "Cancel edit", exact: true }).click();
    await mutate("PATCH", "/api/routes/" + id, { methods: [] });
    await refresh();
    await page.getByRole("button", { name: "Edit route " + id, exact: true }).click();
    await page.getByLabel("Request path", { exact: true }).fill("/" + id + "-any");
    assert.equal(await page.locator('input[name="handlers"][value="' + legacyGlobal + '"]').count(), 0);
    await page.locator('input[name="handlers"][value="' + routeHandler.id + '"]').uncheck();
    await page.getByRole("button", { name: "Save route", exact: true }).click();
    await page.locator("#notice").filter({ hasText: `Route "${id}" updated.` }).waitFor();
    assert.equal((await config()).body.routes.find((route) => route.id === id).methods?.length || 0, 0);
    assert.deepEqual((await config()).body.routes.find((route) => route.id === id).handlers, [legacyGlobal], "Changing route-specific bindings must preserve hidden bindings");
    await checkHandlerChoices(page, (await config()).body);
    await fill(id + "-retry", "/" + id + "-retry");
    const current = await config();
    const external = await fetch(base + "/api/routes", { method: "POST", headers: { "Origin": base, "Content-Type": "application/json", "If-Match": current.etag }, body: JSON.stringify({ id: id + "-external", path: "/" + id + "/<img src=x onerror=window.uiXss=1>", upstream: saved.upstream, handlers: [], methods: ["GET"], prefix: false, strip_prefix: false }) });
    assert.ok(external.ok, await external.text());
    await submit.click();
    await page.locator("#notice").filter({ hasText: "Configuration changed while you were editing" }).waitFor();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).inputValue(), id + "-retry");
    assert.equal(await page.evaluate(() => window.uiXss), undefined);
    await submit.click();
    await page.locator("#notice").filter({ hasText: `Route "${id}-retry" created.` }).waitFor();
    await fill(id + "-invalid", "/api//invalid");
    await submit.click();
    await page.locator("#notice.error").waitFor();
    assert.equal(await page.getByLabel("Route ID", { exact: true }).inputValue(), id + "-invalid");
    assert.ok(!(await config()).body.routes.some((route) => route.id === id + "-invalid"));
    await page.locator("#search").fill(id);
    assert.equal(await page.locator("#routes tr").count(), 3);
    await page.locator("#search").fill("");
    await page.getByRole("button", { name: "Delete route " + id + "-retry", exact: true }).click();
    await page.locator("#delete-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.ok((await config()).body.routes.some((route) => route.id === id + "-retry"));
    await page.getByRole("button", { name: "Delete route " + id + "-retry", exact: true }).click();
    const deleteState = await config();
    const concurrent = await fetch(base + "/api/upstreams", { method: "POST", headers: { "Origin": base, "Content-Type": "application/json", "If-Match": deleteState.etag }, body: JSON.stringify({ id: id + "-concurrent", targets: [{ id: "a", url: before.body.upstreams[0].targets[0].url }] }) });
    assert.ok(concurrent.ok, await concurrent.text());
    await page.locator("#confirm-delete").click();
    await page.locator("#delete-error").filter({ hasText: "Configuration changed" }).waitFor();
    await page.locator("#confirm-delete").click();
    await page.locator("#notice").filter({ hasText: `Route "${id}-retry" deleted.` }).waitFor();
    assert.ok(!(await config()).body.routes.some((route) => route.id === id + "-retry"));
    await page.getByRole("button", { name: "Upstreams", exact: true }).click();
    await page.getByRole("button", { name: "Delete upstream " + selectedUpstream, exact: true }).click();
    await page.locator("#delete-error").filter({ hasText: "Remove these routes first:" }).waitFor();
    assert.ok((await page.locator("#delete-error").textContent()).includes(id + "-external"));
    assert.equal(await page.locator("#confirm-delete").isDisabled(), true);
    await page.locator("#delete-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    // The API must enforce dependencies even when a caller bypasses the disabled button.
    const referenced = await config();
    const rejected = await fetch(base + "/api/upstreams/" + selectedUpstream, { method: "DELETE", headers: { Origin: base, "If-Match": referenced.etag } });
    assert.equal(rejected.status, 422);
    assert.ok((await config()).body.upstreams.some((item) => item.id === selectedUpstream));
    const targets = [{ id: "primary", url: before.body.upstreams[0].targets[0].url }, { id: "secondary", url: before.body.upstreams[0].targets[0].url + "/base" }];
    await mutate("PATCH", "/api/upstreams/" + selectedUpstream, { targets, max_conns: 17, dial_timeout: "4s", tls: { server_name: "example.com" } });
    await refresh();
    await page.getByRole("button", { name: "Edit upstream " + selectedUpstream, exact: true }).click();
    const backendURL = page.getByLabel("Backend URL · primary", { exact: true });
    await backendURL.fill(targets[0].url + "/edited");
    await mutate("PATCH", "/api/upstreams/" + selectedUpstream, { max_conns: 18 });
    await page.getByRole("button", { name: "Save upstream", exact: true }).click();
    await page.locator("#upstream-error").filter({ hasText: "Configuration changed." }).waitFor();
    assert.equal(await backendURL.inputValue(), targets[0].url + "/edited");
    await page.getByRole("button", { name: "Save upstream", exact: true }).click();
    await page.locator("#upstream-dialog").waitFor({ state: "hidden" });
    let upstream = (await config()).body.upstreams.find((item) => item.id === selectedUpstream);
    assert.equal(upstream.max_conns, 18); assert.equal(upstream.dial_timeout, "4s"); assert.equal(upstream.tls.server_name, "example.com");
    assert.deepEqual(upstream.targets, [{ id: "primary", url: targets[0].url + "/edited" }, targets[1]]);
    await page.getByRole("button", { name: "Edit upstream " + selectedUpstream, exact: true }).click();
    await backendURL.fill("ftp://example.com");
    await page.getByRole("button", { name: "Save upstream", exact: true }).click();
    await page.locator("#upstream-error").waitFor({ state: "visible" });
    assert.deepEqual((await config()).body.upstreams.find((item) => item.id === selectedUpstream).targets, upstream.targets);
    await page.locator("#upstream-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    // A changed target array cannot be replaced by an older draft after a conflict.
    await page.getByRole("button", { name: "Edit upstream " + selectedUpstream, exact: true }).click();
    await backendURL.fill(targets[0].url + "/draft");
    await mutate("PATCH", "/api/upstreams/" + selectedUpstream, { targets: [...upstream.targets, { id: "concurrent", url: targets[0].url + "/concurrent" }] });
    await page.getByRole("button", { name: "Save upstream", exact: true }).click();
    await page.locator("#upstream-error").filter({ hasText: "Backend targets changed" }).waitFor();
    assert.equal(await page.getByRole("button", { name: "Save upstream", exact: true }).isDisabled(), true);
    assert.equal(await backendURL.inputValue(), targets[0].url + "/draft");
    await page.locator("#upstream-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    await page.getByRole("button", { name: "Edit upstream " + selectedUpstream, exact: true }).click();
    await page.getByRole("button", { name: "Remove backend secondary", exact: true }).click();
    await page.getByRole("button", { name: "Add backend", exact: false }).click();
    await page.getByLabel("Backend URL · target-1", { exact: true }).fill(targets[0].url + "/new");
    await page.getByRole("button", { name: "Save upstream", exact: true }).click();
    await page.locator("#upstream-dialog").waitFor({ state: "hidden" });
    upstream = (await config()).body.upstreams.find((item) => item.id === selectedUpstream);
    assert.deepEqual(upstream.targets.map((target) => target.id), ["primary", "concurrent", "target-1"]);
    await page.locator("#upstream-search").fill(selectedUpstream);
    assert.equal(await page.locator("#upstreams tr").count(), 1);
    await page.locator("#upstream-search").fill("");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile upstreams overflow horizontally");
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/upstreams-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1080 });
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/upstreams-desktop.png", fullPage: true });
    for (const routeID of [id, id + "-external"]) await mutate("DELETE", "/api/routes/" + routeID);
    await refresh();
    await page.getByRole("button", { name: "Delete upstream " + selectedUpstream, exact: true }).click();
    await page.locator("#delete-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    assert.ok((await config()).body.upstreams.some((item) => item.id === selectedUpstream));
    await page.getByRole("button", { name: "Delete upstream " + selectedUpstream, exact: true }).click();
    // Another writer adds a dependency between opening and confirming the dialog.
    await mutate("POST", "/api/routes", { id: id + "-late", path: "/" + id + "-late", upstream: selectedUpstream, handlers: [], methods: ["GET"] });
    await page.locator("#confirm-delete").click();
    await page.locator("#delete-error").filter({ hasText: id + "-late" }).waitFor();
    assert.equal(await page.locator("#confirm-delete").isDisabled(), true);
    await page.locator("#delete-dialog").getByRole("button", { name: "Cancel", exact: true }).click();
    await mutate("DELETE", "/api/routes/" + id + "-late");
    await refresh();
    await page.getByRole("button", { name: "Delete upstream " + selectedUpstream, exact: true }).click();
    await page.locator("#confirm-delete").click();
    await page.locator("#notice").filter({ hasText: `Upstream "${selectedUpstream}" deleted.` }).waitFor();
    assert.ok(!(await config()).body.upstreams.some((item) => item.id === selectedUpstream));
    await page.getByRole("button", { name: "Add upstream", exact: false }).click();
    await page.getByLabel("Upstream ID", { exact: true }).fill(id + "-standalone");
    await page.getByLabel("Backend URLs", { exact: true }).fill(targets[0].url);
    await page.getByRole("button", { name: "Create upstream", exact: true }).click();
    await page.locator("#upstream-dialog").waitFor({ state: "hidden" });
    assert.ok((await config()).body.upstreams.some((item) => item.id === id + "-standalone"));
    await page.getByRole("button", { name: "Routes", exact: true }).click();
    await page.locator("#route-form").evaluate((form) => form.reset());
    await page.getByRole("button", { name: "Refresh" }).click();
    await page.locator("#notice").filter({ hasText: "Configuration refreshed." }).waitFor();
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile page overflows horizontally");
    if (process.env.ROUTETUS_UI_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ROUTETUS_UI_SCREENSHOT_DIR + "/mobile.png", fullPage: true });
    assert.deepEqual(errors, []);
    console.log("Browser checks passed: Routes/Upstreams tabs, CRUD, field and target preservation, handler order, generation conflicts, dependency deletion guards, route-only handler guide, validation, safe text, filtering, and mobile layout.");
  } finally { await browser.close(); }
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
