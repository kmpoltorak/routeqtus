"""Generate field coverage from the OpenAPI contract, without a second field list."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
document = json.loads((root / "docs/openapi.json").read_text())
schemas = document["components"]["schemas"]


def rows(schema, prefix=""):
    if "$ref" in schema:
        schema = schemas[schema["$ref"].rsplit("/", 1)[1]]
    for name, value in schema.get("properties", {}).items():
        field = f"{prefix}.{name}" if prefix else name
        required = name in schema.get("required", [])
        default = json.dumps(value["default"]) if "default" in value else "none / see description"
        kind = value.get("type", "object")
        null = "inherit/default" if value.get("nullable") else "rejected; PATCH removes optional fields"
        description = value.get("description", "")
        limits = [f"{key}={value[key]}" for key in ("minimum", "maximum", "minItems", "maxItems", "minLength", "maxLength") if key in value]
        if "enum" in value:
            limits.append(f"enum={value['enum']}")
        if "pattern" in value:
            limits.append(f"pattern `{value['pattern']}`")
        description += (" " + "; ".join(limits)) if limits else ""
        endpoint = "/v1/config"
        first = field.split(".")[0]
        for collection in ("routes", "upstreams", "handlers"):
            if first.startswith(collection):
                endpoint += f"; /v1/{collection}/{{id}}"
        if first in ("metrics", "trusted_proxies"):
            endpoint += "; /v1/settings"
        if first == "global_handlers":
            endpoint += "; /v1/global-handlers"
        yield [field, endpoint, kind, "yes" if required else "no", default, null, description]
        nested = value.get("items", value) if kind == "array" else value
        if "properties" in nested:
            yield from rows(nested, field + ("[]" if kind == "array" else ""))


intro = """# Configuration reference

## Operational fields

Generated by `make docs` from the actual typed OpenAPI schemas. All fields are
available through full configuration GET/PUT/PATCH. Entity endpoints support
CRUD; target endpoints are `/v1/upstreams/{id}/targets/{target_id}`. Route binding
order is also exposed at `/v1/routes/{id}/handlers`.

The default column describes omission. `null` on nullable overrides removes the
override. PATCH `null` on optional non-nullable fields removes the field and restores
its omission default; removing a required field is rejected. Arrays replace as a
whole. Empty arrays are explicit values. Durations are strings in Go units, range
0s–24h; explicit 0s disables operational timeouts. Bootstrap timeouts must be positive.

Configured GET values retain omission; effective GET resolves transport, handler,
metrics, and route deadline defaults. Export configured values for re-import.
Secret values are never part of this contract: TLS fields name environment variables,
not PEM contents. Placeholder names such as `***` are invalid references.

"""
table = ["| Field | Endpoint/schema | Type | Required | Default | Null | Meaning / constraints |", "| --- | --- | --- | --- | --- | --- | --- |"]
for row in rows(schemas["Config"]):
    table.append("| " + " | ".join(str(x).replace("|", "\\|").replace("\n", " ") for x in row) + " |")
table.extend(["", "## Handler instance fields", ""])
handler = schemas["Handler"]["oneOf"][0]
for row in rows(handler):
    if row[0] == "options":
        row[6] = "Options are determined by the handler type; see the schemas below."
    table.append("- `" + row[0] + "`: " + row[6] + " Required: " + row[3] + ". Default: " + row[4] + ".")
for name, schema in sorted(schemas.items()):
    if name.startswith("HandlerOptions_"):
        kind = name.removeprefix("HandlerOptions_")
        table.extend(["", f"## Handler options: {kind}", "", f"`GET /v1/handler-types/{kind}/schema` (contract version 1).", "", "| Field | Type | Required | Default | Meaning |", "| --- | --- | --- | --- | --- |"])
        found = False
        for row in rows(schema):
            found = True
            table.append("| " + " | ".join(str(row[i]).replace("|", "\\|") for i in (0, 2, 3, 4, 6)) + " |")
        if not found:
            table.append("| `{}` | object | yes | empty object | No options; unknown keys are rejected. |")
